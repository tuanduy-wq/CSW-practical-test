package com.fpt.csw.controller;

import com.fpt.csw.dao.EmployeeDAO;
import com.fpt.csw.model.Employee;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.sql.SQLException;
import java.util.List;
import java.util.Map;

/**
 * REST web service for employees.
 *   GET  /api/employees  -> getEmployees
 *   POST /api/employees  -> addEmployees
 *   PUT  /api/employees  -> updateEmployee
 */
@RestController
@RequestMapping("/api/employees")
public class EmployeeController {

    private final EmployeeDAO dao = new EmployeeDAO();

    /** getEmployees: retrieve all employees as a JSON array. */
    @GetMapping
    public ResponseEntity<?> getEmployees() {
        try {
            List<Employee> employees = dao.findAll();
            return ResponseEntity.ok(employees);
        } catch (SQLException ex) {
            return error(HttpStatus.INTERNAL_SERVER_ERROR, "Database error: " + ex.getMessage());
        }
    }

    /** addEmployees: add a new employee (id is generated by the database). */
    @PostMapping
    public ResponseEntity<?> addEmployees(@RequestBody Employee e) {
        String problem = validate(e);
        if (problem != null) {
            return error(HttpStatus.BAD_REQUEST, problem);
        }
        try {
            return ResponseEntity.status(HttpStatus.CREATED).body(dao.insert(e));
        } catch (SQLException ex) {
            return error(HttpStatus.INTERNAL_SERVER_ERROR, "Database error: " + ex.getMessage());
        }
    }

    /** updateEmployee: modify an existing employee identified by e.id. */
    @PutMapping
    public ResponseEntity<?> updateEmployee(@RequestBody Employee e) {
        String problem = validate(e);
        if (problem != null) {
            return error(HttpStatus.BAD_REQUEST, problem);
        }
        if (e.getId() <= 0) {
            return error(HttpStatus.BAD_REQUEST, "A valid employee id is required.");
        }
        try {
            if (dao.update(e)) {
                return ResponseEntity.ok(e);
            }
            return error(HttpStatus.NOT_FOUND, "Employee with id " + e.getId() + " not found.");
        } catch (SQLException ex) {
            return error(HttpStatus.INTERNAL_SERVER_ERROR, "Database error: " + ex.getMessage());
        }
    }

    // ---------- helpers ----------

    private String validate(Employee e) {
        if (e == null || e.getName() == null || e.getName().trim().isEmpty()) {
            return "Name must not be empty.";
        }
        if (e.getSalary() < 0) {
            return "Salary must not be negative.";
        }
        return null;
    }

    private ResponseEntity<Map<String, String>> error(HttpStatus status, String message) {
        return ResponseEntity.status(status).body(Map.of("error", message));
    }
}